// The closing number is the one that makes someone act. A percentage of a whole
// codebase is abstract; "N lines of AI-written auth code, live, unreviewed" is
// not. Prefer the most sensitive surface the real scan actually found, and fall
// back to the total only when no sensitive surface was hit.
const SENSITIVE_LABELS: Record<string, string> = {
  auth: 'authentication code',
  secrets: 'credential-handling code',
  payments: 'payment code',
  shell: 'shell-executing code',
  sql: 'raw-SQL code',
};

const categories = scan.byCategory as Record<string, { lines: number; files: number }>;

// Pick the sensitive surface carrying the most AI lines — the biggest true
// finding, rather than whichever slug happens to sort first.
const headlineSurface = Object.keys(SENSITIVE_LABELS)
  .filter((slug) => (categories[slug]?.lines ?? 0) > 0)
  .sort((a, b) => categories[b].lines - categories[a].lines)[0];

const closing = headlineSurface
  ? {
    value: categories[headlineSurface].lines,
    label: `lines of AI-written ${SENSITIVE_LABELS[headlineSurface]} are live in this repo right now`,
    detail: `across ${categories[headlineSurface].files} ${categories[headlineSurface].files === 1 ? 'file' : 'files'} — with no prompt, no model, and no review state on record`,
  }
  : {
    value: scan.totals.aiAttributedLines,
    label: 'lines of AI-written code are live in this repo right now',
    detail: 'with no prompt, no model, and no review state on record',
  };

