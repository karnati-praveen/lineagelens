'use strict';

const fs = require('fs');
const path = require('path');

const {
  filterRecordsForFile,
  blameLines,
  computeStats,
} = require('../blame/lineagelens-cli-blame-engine');
const { loadRecords } = require('../blame/lineagelens-cli-record-source');
const { isJsonMode, out, err } = require('../utils/lineagelens-cli-output');

// Directories that never contain first-party source worth attributing.
const SKIP_DIRS = new Set([
  'node_modules', '.git', '.hg', '.svn', 'dist', 'out', 'build', 'coverage',
  '__pycache__', '.venv', 'venv', '.tox', '.mypy_cache', '.pytest_cache',
  '.next', '.nuxt', 'target', 'vendor', '.idea', '.vscode',
]);

const MAX_FILE_BYTES = 1024 * 1024; // skip files over 1 MB

/** Cheap binary check: NUL byte in the first 8 KB. */
function looksBinary(buf) {
  const probe = buf.subarray(0, 8192);
  return probe.includes(0);
}

/** Recursively collect candidate source files under root. */
function walkFiles(root) {
  const found = [];
  const stack = [root];
  while (stack.length > 0) {
    const dir = stack.pop();
    let entries;
    try {
      entries = fs.readdirSync(dir, { withFileTypes: true });
    } catch {
      continue;
    }
    for (const entry of entries) {
      if (entry.name.startsWith('.') && entry.name !== '.github') {
        if (entry.isDirectory()) continue;
      }
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        if (!SKIP_DIRS.has(entry.name)) stack.push(full);
      } else if (entry.isFile()) {
        found.push(full);
      }
    }
  }
  return found;
}

/**
 * Group records by basename so the per-file scan only blames files that have
 * at least one plausible record — this keeps repo-wide runs fast.
 */
function recordsByBasename(records) {
  const map = new Map();
  for (const r of records) {
    const base = String(r.filePath || '').replace(/\\/g, '/').split('/').pop().toLowerCase();
    if (!base) continue;
    if (!map.has(base)) map.set(base, []);
    map.get(base).push(r);
  }
  return map;
}

function makePalette(useColor) {
  const wrap = (code) => (s) => (useColor ? `\x1b[${code}m${s}\x1b[0m` : s);
  return { green: wrap('32'), cyan: wrap('36'), dim: wrap('2'), bold: wrap('1') };
}

function bar(percent, width = 20) {
  const filled = Math.round((percent / 100) * width);
  return '█'.repeat(filled) + '░'.repeat(width - filled);
}

function renderTerminal(rootLabel, rows, totals, palette, topN, activeFilters) {
  const lines = [];
  lines.push(palette.bold(`── lineagelens report ─ ${rootLabel}`));
  lines.push('');
  const shown = rows.slice(0, topN);
  const pathWidth = Math.max(4, ...shown.map((r) => r.file.length));
  for (const row of shown) {
    const pct = `${row.percent}%`.padStart(6);
    lines.push(
      `  ${row.file.padEnd(pathWidth)}  ${palette.green(bar(row.percent))} ${pct}  ` +
      palette.dim(`${row.aiLines}/${row.totalLines} lines`),
    );
  }
  if (rows.length > shown.length) {
    lines.push(palette.dim(`  … and ${rows.length - shown.length} more attributed file${rows.length - shown.length !== 1 ? 's' : ''} (use --top to show more)`));
  }
  lines.push('');
  const filterSuffix = activeFilters.length > 0 ? ` — filter: ${activeFilters.join(', ')}` : '';
  lines.push(palette.bold(
    `  Repo total: ${totals.aiLines}/${totals.totalLines} lines AI-attributed (${totals.percent}%) across ` +
    `${rows.length} of ${totals.filesScanned} scanned files${filterSuffix}`,
  ));
  for (const m of totals.byModel) {
    lines.push(`    ${palette.cyan(m.model)}: ${m.lines} lines`);
  }
  if (rows.length === 0) {
    lines.push(palette.dim('  No provenance records matched any scanned file.'));
  }
  return lines.join('\n');
}

function renderMarkdown(rootLabel, rows, totals, topN) {
  const lines = [];
  lines.push(`## AI Attribution Report — ${rootLabel}`);
  lines.push('');
  lines.push(`**${totals.percent}%** of attributed code lines are AI-generated ` +
    `(${totals.aiLines}/${totals.totalLines} lines, ${rows.length} of ${totals.filesScanned} scanned files).`);
  lines.push('');
  lines.push('| File | AI lines | Total lines | AI % |');
  lines.push('|---|---:|---:|---:|');
  for (const row of rows.slice(0, topN)) {
    lines.push(`| \`${row.file}\` | ${row.aiLines} | ${row.totalLines} | ${row.percent}% |`);
  }
  if (totals.byModel.length > 0) {
    lines.push('');
    lines.push('**By model:** ' + totals.byModel.map((m) => `${m.model} (${m.lines})`).join(', '));
  }
  lines.push('');
  lines.push('_Generated by [`lineagelens report`](https://github.com/karnati-praveen/lineagelens)._');
  return lines.join('\n');
}

/**
 * lineagelens report [dir] — repo-wide AI attribution.
 *
 * Walks the directory, blames every file that has at least one matching
 * provenance record, and prints a per-file + per-model summary. `--md` emits
 * a paste-ready markdown report; global `--json` emits machine output.
 */
async function report(dir, opts) {
  const root = path.resolve(dir || '.');
  if (!fs.existsSync(root) || !fs.statSync(root).isDirectory()) {
    err(`Not a directory: ${root}`);
    process.exit(1);
  }

  let loaded;
  try {
    loaded = await loadRecords(opts, null);
  } catch (e) {
    err(e.message);
    process.exit(1);
  }

  const minConfidence = typeof opts.minConfidence === 'number' && !Number.isNaN(opts.minConfidence)
    ? opts.minConfidence
    : null;

  const byBase = recordsByBasename(loaded.records);
  const files = walkFiles(root);

  const rows = [];
  const modelTotals = new Map();
  let totalLines = 0;
  let aiLines = 0;
  let scanned = 0;

  for (const file of files) {
    const base = path.basename(file).toLowerCase();
    const candidates = byBase.get(base);
    if (!candidates || candidates.length === 0) continue;

    let buf;
    try {
      buf = fs.readFileSync(file);
    } catch {
      continue;
    }
    if (buf.length > MAX_FILE_BYTES || looksBinary(buf)) continue;
    scanned++;

    const fileRecords = filterRecordsForFile(candidates, file);
    if (fileRecords.length === 0) continue;

    const blame = blameLines(buf.toString('utf-8'), fileRecords, { minConfidence });
    const stats = computeStats(blame);
    totalLines += stats.totalLines;
    aiLines += stats.aiLines;
    if (stats.aiLines === 0) continue;

    for (const m of stats.byModel) {
      modelTotals.set(m.model, (modelTotals.get(m.model) || 0) + m.lines);
    }
    rows.push({
      file: path.relative(root, file).replace(/\\/g, '/'),
      aiLines: stats.aiLines,
      totalLines: stats.totalLines,
      exactLines: stats.exactLines,
      partialLines: stats.partialLines,
      percent: stats.percent,
    });
  }

  rows.sort((a, b) => b.aiLines - a.aiLines || b.percent - a.percent);

  const totals = {
    filesScanned: scanned,
    filesAttributed: rows.length,
    totalLines,
    aiLines,
    percent: totalLines > 0 ? Math.round((aiLines / totalLines) * 1000) / 10 : 0,
    byModel: [...modelTotals.entries()]
      .map(([model, lines]) => ({ model, lines }))
      .sort((a, b) => b.lines - a.lines),
  };

  const topN = Number.parseInt(opts.top, 10) > 0 ? Number.parseInt(opts.top, 10) : 25;
  const rootLabel = path.basename(root) || root;

  const activeFilters = [];
  if (opts.reviewStatus) activeFilters.push(opts.reviewStatus);
  if (opts.category) activeFilters.push(opts.category);

  if (isJsonMode()) {
    out({ root, recordSource: loaded.format, warnings: loaded.warnings, totals, files: rows, filters: { reviewStatus: opts.reviewStatus || null, category: opts.category || null } });
    return;
  }
  for (const warning of loaded.warnings) {
    err(`note: ${warning}`);
  }
  if (opts.md) {
    out(renderMarkdown(rootLabel, rows, totals, topN));
    return;
  }
  const palette = makePalette(opts.color !== false && process.stdout.isTTY);
  out(renderTerminal(rootLabel, rows, totals, palette, topN, activeFilters));
}

module.exports = { report, walkFiles, recordsByBasename };
